// bun scripts/check-env.ts [path/to/.env]   -> lists missing variables by group (exit 1 if a required one is missing)
// bun scripts/check-env.ts --markdown       -> prints docs/release/env-matrix.md
import { existsSync, readFileSync } from "node:fs";
import { ENV_VARS } from "./env-registry";

export function parseDotenv(text: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) continue;
    const m = /^(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/.exec(line);
    if (!m) continue;
    out[m[1]!] = m[2]!.replace(/^(['"])(.*)\1$/, "$2");
  }
  return out;
}

export function missing(env: Record<string, string | undefined>) {
  return ENV_VARS.filter(
    (v) => v.status !== "retiring" && v.group !== "Tests" && !env[v.name]?.trim(),
  );
}

export function markdown(): string {
  const rows = ENV_VARS.map((v) => `| ${v.group} | \`${v.name}\` | ${v.status} | ${v.note} |`);
  return [
    "# Environment variables",
    "",
    "Generated by `bun scripts/check-env.ts --markdown` from `scripts/env-registry.ts`. Set them in Vercel → Project → Settings → Environment Variables.",
    "",
    "| Group | Variable | Status | Note |",
    "| --- | --- | --- | --- |",
    ...rows,
    "",
  ].join("\n");
}

if (import.meta.main) {
  const arg = process.argv[2];
  if (arg === "--markdown") {
    process.stdout.write(markdown());
  } else {
    const env = arg && existsSync(arg) ? parseDotenv(readFileSync(arg, "utf8")) : process.env;
    const gaps = missing(env);
    const byGroup = new Map<string, string[]>();
    for (const g of gaps)
      byGroup.set(g.group, [...(byGroup.get(g.group) ?? []), `${g.name} (${g.status})`]);
    for (const [g, names] of byGroup) console.log(`${g}: ${names.join(", ")}`);
    if (!gaps.length) console.log("All required and feature variables are set.");
    process.exit(gaps.some((g) => g.status === "required") ? 1 : 0);
  }
}
