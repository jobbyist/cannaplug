import { AUTHOR_NAME } from "../src/lib/journal-launch-articles";
import { SCHEDULED_ARTICLES, type ScheduledArticle } from "../src/lib/journal-scheduled-articles";

/**
 * Builds supabase/migrations/20261028007000_journal_scheduled_articles.sql from src/lib/journal-scheduled-articles.ts.
 *   bun scripts/journal-scheduled-migration.ts   -> writes the migration and its drizzle mirror
 * A test fails if the committed files differ from what this produces.
 *
 * Adds rows only (no DROP, no DELETE), so the hosted Supabase connector applies it without a confirmation.
 */
export const MIGRATION_NAME = "20261028007000_journal_scheduled_articles";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const dq = (s: string) => {
  if (s.includes("$jb$") || s.includes("$$"))
    throw new Error("article text contains a dollar-quote tag");
  return `$jb$${s}$jb$`;
};
const textArray = (xs: string[]) => `ARRAY[${xs.map(q).join(", ")}]::text[]`;

const HEAD = `-- 28 Oct 2026: three Journal articles by ${AUTHOR_NAME}, scheduled for 8:00 AM SAST on 29, 30 and 31 October 2026.
--   Each row is inserted now with its future published_at. The public Journal only lists and opens articles whose
--   published_at has passed, so each one appears by itself at 8:00 AM SAST; nothing has to be run on the day.
--   Photos are fetched by the admin "Fetch article images" action (it works from image_queries).
--   Rows only: no DROP and no DELETE. Generated by scripts/journal-scheduled-migration.ts from
--   src/lib/journal-scheduled-articles.ts.
`;

function articleInsert(a: ScheduledArticle): string {
  return `INSERT INTO public.articles
  (slug, title, excerpt, body_md, category, reading_minutes, published_at, author_name, keywords, featured,
   updated_at, sources, image_queries)
VALUES (
  ${q(a.slug)},
  ${q(a.title)},
  ${q(a.excerpt)},
  ${dq(a.body_md)},
  ${q(a.category)},
  ${a.reading_minutes},
  ${q(a.published_at)}::timestamptz,
  ${q(AUTHOR_NAME)},
  ${textArray(a.keywords)},
  false,
  ${q(a.published_at)}::timestamptz,
  ${dq(JSON.stringify(a.sources))}::jsonb,
  ${dq(JSON.stringify(a.image_queries))}::jsonb)
ON CONFLICT (slug) DO NOTHING;
`;
}

export function buildScheduledArticlesMigration(): string {
  return `${HEAD}\n${SCHEDULED_ARTICLES.map(articleInsert).join("\n")}`;
}

if (import.meta.main) {
  const { writeFileSync } = await import("node:fs");
  const sql = buildScheduledArticlesMigration();
  writeFileSync(new URL(`../supabase/migrations/${MIGRATION_NAME}.sql`, import.meta.url), sql);
  writeFileSync(
    new URL("../drizzle/migrations/0052_journal_scheduled_articles.sql", import.meta.url),
    sql,
  );
  console.log(`wrote ${MIGRATION_NAME} (${sql.length} bytes)`);
}
