import { AUTHOR_NAME, LAUNCH_ARTICLES } from "../src/lib/journal-launch-articles";

/**
 * Builds supabase/migrations/20261028003000_journal_engagement.sql from src/lib/journal-launch-articles.ts.
 *   bun scripts/journal-migration.ts   -> writes the migration and its drizzle mirror
 * A test fails if the committed files differ from what this produces.
 *
 * Deliberately no DROP and no row DELETE statements: the hosted Supabase connector holds any statement that
 * contains one for an interactive confirmation, and nothing here needs them (an "unlike" is liked = false).
 */
export const MIGRATION_NAME = "20261028003000_journal_engagement";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
// Dollar-quoted literal; the tag cannot occur in the text.
const dq = (s: string) => {
  if (s.includes("$jb$") || s.includes("$$"))
    throw new Error("article text contains a dollar-quote tag");
  return `$jb$${s}$jb$`;
};
const textArray = (xs: string[]) => `ARRAY[${xs.map(q).join(", ")}]::text[]`;

const HEAD = `-- 28 Oct 2026: Journal articles with an author, likes, comments, sharing and featured stories.
--   * articles gain author_name, keywords, featured, updated_at, cover_alt, inline_images (photos placed between
--     paragraphs, with credit) and image_queries (what to search for on Unsplash).
--   * article_likes: one row per member and article (liked true/false, so "unlike" needs no row deletion).
--   * article_comments: member comments (display name is first name + last initial) plus clearly flagged seed
--     comments (is_seed). A moderator can hide a comment; nothing is ever hard-deleted.
--   * Both tables have RLS on and NO browser grants: reads and writes go through server functions that call the
--     service-role-only functions below (actor argument, audit row, rate limit). Only signed-in members can like
--     or comment; the actor always comes from the verified session, never from the browser.
--   * Four launch articles by ${AUTHOR_NAME} (25-28 Oct 2026) with 1-3 seeded comments each. Photos are fetched
--     later by the admin "Fetch article images" action, server-side, with UNSPLASH_ACCESS_KEY.
--   Generated by scripts/journal-migration.ts from src/lib/journal-launch-articles.ts.

ALTER TABLE public.articles
  ADD COLUMN IF NOT EXISTS author_name text,
  ADD COLUMN IF NOT EXISTS keywords text[] NOT NULL DEFAULT '{}',
  ADD COLUMN IF NOT EXISTS featured boolean NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS updated_at timestamptz,
  ADD COLUMN IF NOT EXISTS cover_alt text,
  ADD COLUMN IF NOT EXISTS inline_images jsonb NOT NULL DEFAULT '[]'::jsonb,
  ADD COLUMN IF NOT EXISTS image_queries jsonb NOT NULL DEFAULT '[]'::jsonb;
CREATE INDEX IF NOT EXISTS articles_featured_idx ON public.articles (featured, published_at DESC);

CREATE TABLE IF NOT EXISTS public.article_likes (
  article_id uuid NOT NULL REFERENCES public.articles(id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  liked boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (article_id, user_id)
);
CREATE INDEX IF NOT EXISTS article_likes_user_idx ON public.article_likes (user_id);

CREATE TABLE IF NOT EXISTS public.article_comments (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  article_id uuid NOT NULL REFERENCES public.articles(id) ON DELETE CASCADE,
  user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  display_name text NOT NULL CHECK (length(btrim(display_name)) BETWEEN 1 AND 60),
  body text NOT NULL CHECK (length(btrim(body)) BETWEEN 2 AND 1000),
  is_seed boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  hidden_at timestamptz,
  hidden_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  hide_reason text CHECK (hide_reason IS NULL OR length(btrim(hide_reason)) BETWEEN 3 AND 200),
  CONSTRAINT article_comments_author_chk CHECK (user_id IS NOT NULL OR is_seed)
);
CREATE INDEX IF NOT EXISTS article_comments_article_idx ON public.article_comments (article_id, created_at);
CREATE INDEX IF NOT EXISTS article_comments_user_idx ON public.article_comments (user_id, created_at DESC);

ALTER TABLE public.article_likes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.article_comments ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.article_likes, public.article_comments FROM PUBLIC, anon, authenticated;
GRANT ALL ON public.article_likes, public.article_comments TO service_role;

-- Like or unlike (idempotent by nature: it sets a state). Any signed-in member.
CREATE OR REPLACE FUNCTION public.article_set_like(p_actor uuid, p_article_id uuid, p_liked boolean)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $fn$
DECLARE
  v_before boolean;
  v_count integer;
BEGIN
  IF p_actor IS NULL OR NOT EXISTS (SELECT 1 FROM auth.users WHERE id = p_actor) THEN
    RAISE EXCEPTION 'forbidden: sign in to like articles' USING ERRCODE = '42501';
  END IF;
  IF p_liked IS NULL THEN RAISE EXCEPTION 'invalid_input'; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.articles WHERE id = p_article_id AND published_at <= now()) THEN
    RAISE EXCEPTION 'article_not_found';
  END IF;
  SELECT liked INTO v_before FROM public.article_likes WHERE article_id = p_article_id AND user_id = p_actor;
  INSERT INTO public.article_likes (article_id, user_id, liked)
  VALUES (p_article_id, p_actor, p_liked)
  ON CONFLICT (article_id, user_id) DO UPDATE SET liked = EXCLUDED.liked, updated_at = now();
  IF v_before IS DISTINCT FROM p_liked THEN
    PERFORM public._audit(p_actor, CASE WHEN p_liked THEN 'article_liked' ELSE 'article_unliked' END,
                          'article', p_article_id, '{}'::jsonb);
  END IF;
  SELECT count(*) INTO v_count FROM public.article_likes WHERE article_id = p_article_id AND liked;
  RETURN jsonb_build_object('liked', p_liked, 'like_count', v_count);
END;
$fn$;

-- Add a comment. Signed-in members only; at most 5 per 10 minutes; no repeats; no link spam.
CREATE OR REPLACE FUNCTION public.article_add_comment(
  p_actor uuid, p_article_id uuid, p_body text, p_idempotency_key text
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $fn$
DECLARE
  v_cached jsonb;
  v_body text := btrim(COALESCE(p_body, ''));
  v_full text;
  v_parts text[];
  v_name text;
  v_id uuid;
  v_response jsonb;
BEGIN
  IF p_actor IS NULL OR NOT EXISTS (SELECT 1 FROM auth.users WHERE id = p_actor) THEN
    RAISE EXCEPTION 'forbidden: sign in to comment' USING ERRCODE = '42501';
  END IF;
  v_cached := public._idem_begin('article_comment', p_actor, p_idempotency_key,
    jsonb_build_object('a', p_article_id, 'b', v_body));
  IF v_cached IS NOT NULL THEN RETURN v_cached || jsonb_build_object('replayed', true); END IF;

  IF length(v_body) NOT BETWEEN 2 AND 1000 THEN
    RAISE EXCEPTION 'invalid_input: a comment must be 2 to 1000 characters';
  END IF;
  IF v_body ~ '[\\x01-\\x08\\x0b\\x0c\\x0e-\\x1f]' THEN
    RAISE EXCEPTION 'invalid_input: the comment contains characters that are not allowed';
  END IF;
  IF (length(lower(v_body)) - length(replace(lower(v_body), 'http', ''))) / 4 > 2 THEN
    RAISE EXCEPTION 'invalid_input: please keep links to a minimum';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.articles WHERE id = p_article_id AND published_at <= now()) THEN
    RAISE EXCEPTION 'article_not_found';
  END IF;
  IF (SELECT count(*) FROM public.article_comments
      WHERE user_id = p_actor AND created_at > now() - interval '10 minutes') >= 5 THEN
    RAISE EXCEPTION 'rate_limited: you are commenting very quickly, please wait a few minutes';
  END IF;
  IF EXISTS (SELECT 1 FROM public.article_comments
             WHERE user_id = p_actor AND article_id = p_article_id AND body = v_body
               AND created_at > now() - interval '1 day') THEN
    RAISE EXCEPTION 'duplicate_comment: you already posted that comment';
  END IF;

  -- First name and last initial only ("Thandi M."): no full names, no emails.
  SELECT btrim(full_name) INTO v_full FROM public.profiles WHERE id = p_actor;
  v_parts := string_to_array(COALESCE(v_full, ''), ' ');
  v_name := CASE
    WHEN COALESCE(v_full, '') = '' THEN 'Member'
    WHEN array_length(v_parts, 1) > 1 AND v_parts[array_length(v_parts, 1)] <> ''
      THEN left(v_parts[1], 30) || ' ' || upper(left(v_parts[array_length(v_parts, 1)], 1)) || '.'
    ELSE left(v_parts[1], 30)
  END;

  INSERT INTO public.article_comments (article_id, user_id, display_name, body)
  VALUES (p_article_id, p_actor, v_name, v_body) RETURNING id INTO v_id;
  PERFORM public._audit(p_actor, 'article_comment_added', 'article', p_article_id,
                        jsonb_build_object('comment_id', v_id));
  v_response := jsonb_build_object('comment_id', v_id, 'display_name', v_name);
  RETURN public._idem_finish('article_comment', p_actor, p_idempotency_key, v_response);
END;
$fn$;

-- Moderators (manager and above) can hide a comment, with a reason. It stays in the table.
CREATE OR REPLACE FUNCTION public.article_hide_comment(p_actor uuid, p_comment_id uuid, p_reason text)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $fn$
BEGIN
  PERFORM public._assert_staff(p_actor, 'manager');
  IF p_reason IS NULL OR length(btrim(p_reason)) NOT BETWEEN 3 AND 200 THEN
    RAISE EXCEPTION 'reason_required';
  END IF;
  UPDATE public.article_comments
  SET hidden_at = now(), hidden_by = p_actor, hide_reason = btrim(p_reason)
  WHERE id = p_comment_id AND hidden_at IS NULL;
  IF NOT FOUND THEN RAISE EXCEPTION 'comment_not_found'; END IF;
  PERFORM public._audit(p_actor, 'article_comment_hidden', 'article_comment', p_comment_id,
                        jsonb_build_object('reason', left(btrim(p_reason), 200)));
  RETURN jsonb_build_object('comment_id', p_comment_id, 'hidden', true);
END;
$fn$;

DO $do$
DECLARE f text;
BEGIN
  FOREACH f IN ARRAY ARRAY[
    'public.article_set_like(uuid, uuid, boolean)',
    'public.article_add_comment(uuid, uuid, text, text)',
    'public.article_hide_comment(uuid, uuid, text)']
  LOOP
    EXECUTE format('REVOKE ALL ON FUNCTION %s FROM PUBLIC, anon, authenticated', f);
    EXECUTE format('GRANT EXECUTE ON FUNCTION %s TO service_role', f);
  END LOOP;
END $do$;
`;

function articleInsert(a: (typeof LAUNCH_ARTICLES)[number]): string {
  return `INSERT INTO public.articles
  (slug, title, excerpt, body_md, category, reading_minutes, published_at, author_name, keywords, featured,
   updated_at, sources, image_queries)
VALUES (
  ${q(a.slug)},
  ${q(a.title)},
  ${q(a.excerpt)},
  ${dq(a.body_md)},
  ${q(a.category)},
  ${a.reading_minutes},
  ${q(a.published_at)}::timestamptz,
  ${q(AUTHOR_NAME)},
  ${textArray(a.keywords)},
  true,
  ${q(a.published_at)}::timestamptz,
  ${dq(JSON.stringify(a.sources))}::jsonb,
  ${dq(JSON.stringify(a.image_queries))}::jsonb)
ON CONFLICT (slug) DO NOTHING;
`;
}

function commentInserts(a: (typeof LAUNCH_ARTICLES)[number]): string {
  return a.comments
    .map(
      (
        c,
      ) => `INSERT INTO public.article_comments (article_id, display_name, body, is_seed, created_at)
SELECT a.id, ${q(c.name)}, ${dq(c.body)}, true, a.published_at + interval '${Math.max(0, Math.floor(c.hours_after))} hours'
FROM public.articles a
WHERE a.slug = ${q(a.slug)}
  AND NOT EXISTS (SELECT 1 FROM public.article_comments x
                  WHERE x.article_id = a.id AND x.is_seed AND x.display_name = ${q(c.name)} AND x.body = ${dq(c.body)});
`,
    )
    .join("\n");
}

export function buildJournalMigration(): string {
  const articles = LAUNCH_ARTICLES.map(articleInsert).join("\n");
  const comments = LAUNCH_ARTICLES.map(commentInserts).join("\n");
  return `${HEAD}
-- Launch articles ----------------------------------------------------------------------------------------------
${articles}
-- Seeded comments (flagged is_seed; hide any you do not want from Admin or with article_hide_comment) ----------
${comments}`;
}

if (import.meta.main) {
  const { writeFileSync } = await import("node:fs");
  const sql = buildJournalMigration();
  writeFileSync(new URL(`../supabase/migrations/${MIGRATION_NAME}.sql`, import.meta.url), sql);
  writeFileSync(new URL("../drizzle/migrations/0048_journal_engagement.sql", import.meta.url), sql);
  console.log(`wrote ${MIGRATION_NAME} (${sql.length} bytes)`);
}
